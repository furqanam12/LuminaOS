#!/usr/bin/env python3
"""Generate the Lumina-Dark / Lumina-Light xfwm4 themes (used only by native, non-Lumina apps).
Windows 11-style caption buttons on the right, flat title bar, thin 1px border."""
import os, sys
from PIL import Image, ImageDraw

OUT = sys.argv[1] if len(sys.argv) > 1 else "build/themes"
H = 32      # title height
BW = 46     # button width (Windows 11)
S = 4       # supersampling

THEMES = {
    "Lumina-Dark": dict(bg=(32, 32, 38), bgi=(26, 26, 31), fg=(235, 235, 240), fgi=(140, 140, 150),
                         hov=(255, 255, 255, 26), prs=(255, 255, 255, 16), border=(58, 58, 66), borderi=(44, 44, 50)),
    "Lumina-Light": dict(bg=(243, 243, 246), bgi=(236, 236, 240), fg=(28, 28, 32), fgi=(130, 130, 138),
                          hov=(0, 0, 0, 22), prs=(0, 0, 0, 14), border=(205, 205, 212), borderi=(220, 220, 226)),
}
CLOSE_H, CLOSE_P = (196, 43, 28), (200, 60, 46)


def solid(w, h, c):
    return Image.new("RGBA", (w, h), c + (255,) if len(c) == 3 else c)


def title_piece(t, active, w=H):
    """Title bar slice with 1px top border line."""
    im = solid(w, H, t["bg"] if active else t["bgi"])
    d = ImageDraw.Draw(im)
    d.line([(0, 0), (w, 0)], fill=(t["border"] if active else t["borderi"]) + (255,))
    return im


def glyph(kind, color, size=BW):
    big = Image.new("RGBA", (size * S, H * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    cx, cy, r, lw = size * S // 2, H * S // 2, 5 * S, int(1.1 * S)
    col = color + (255,)
    if kind == "close":
        d.line([(cx - r, cy - r), (cx + r, cy + r)], fill=col, width=lw)
        d.line([(cx - r, cy + r), (cx + r, cy - r)], fill=col, width=lw)
    elif kind == "hide":
        d.line([(cx - r, cy), (cx + r, cy)], fill=col, width=lw)
    elif kind == "maximize":
        d.rounded_rectangle([cx - r, cy - r, cx + r, cy + r], radius=int(1.5 * S), outline=col, width=lw)
    elif kind == "maximize-toggled":
        o = 2 * S
        d.rounded_rectangle([cx - r, cy - r + o, cx + r - o, cy + r], radius=int(1.2 * S), outline=col, width=lw)
        d.line([(cx - r + o, cy - r), (cx + r - S, cy - r)], fill=col, width=lw)
        d.line([(cx + r, cy - r + S), (cx + r, cy + r - o)], fill=col, width=lw)
    elif kind == "menu":
        d.ellipse([cx - 2 * S, cy - 2 * S, cx + 2 * S, cy + 2 * S], fill=col)
    elif kind in ("shade", "stick"):
        d.line([(cx - r, cy + 2 * S), (cx, cy - 2 * S), (cx + r, cy + 2 * S)], fill=col, width=lw)
    elif kind in ("shade-toggled", "stick-toggled"):
        d.line([(cx - r, cy - 2 * S), (cx, cy + 2 * S), (cx + r, cy - 2 * S)], fill=col, width=lw)
    return big.resize((size, H), Image.LANCZOS)


def button(t, kind, state):
    active = state != "inactive"
    w = BW if kind not in ("menu", "shade", "stick", "shade-toggled", "stick-toggled") else 34
    base = title_piece(t, active, w)
    over = Image.new("RGBA", base.size, (0, 0, 0, 0))
    od = ImageDraw.Draw(over)
    fg = t["fg"] if active else t["fgi"]
    if state in ("prelight", "pressed"):
        if kind == "close":
            od.rectangle([0, 1, w, H], fill=(CLOSE_H if state == "prelight" else CLOSE_P) + (255,))
            fg = (255, 255, 255)
        else:
            od.rectangle([0, 1, w, H], fill=t["hov"] if state == "prelight" else t["prs"])
    base = Image.alpha_composite(base, over)
    return Image.alpha_composite(base, glyph(kind, fg, w))


def build(name, t):
    d = os.path.join(OUT, name, "xfwm4")
    os.makedirs(d, exist_ok=True)
    for act, suf in ((True, "active"), (False, "inactive")):
        bc = (t["border"] if act else t["borderi"]) + (255,)
        bg = (t["bg"] if act else t["bgi"]) + (255,)
        for i in range(1, 6):
            title_piece(t, act, 8).save(f"{d}/title-{i}-{suf}.png")
        # corners: 1px border on the outside edge
        tl = title_piece(t, act, 1); ImageDraw.Draw(tl).line([(0, 0), (0, H)], fill=bc); tl.save(f"{d}/top-left-{suf}.png")
        tr = title_piece(t, act, 1); ImageDraw.Draw(tr).line([(0, 0), (0, H)], fill=bc); tr.save(f"{d}/top-right-{suf}.png")
        Image.new("RGBA", (1, 8), bc).save(f"{d}/left-{suf}.png")
        Image.new("RGBA", (1, 8), bc).save(f"{d}/right-{suf}.png")
        Image.new("RGBA", (8, 1), bc).save(f"{d}/bottom-{suf}.png")
        Image.new("RGBA", (1, 1), bc).save(f"{d}/bottom-left-{suf}.png")
        Image.new("RGBA", (1, 1), bc).save(f"{d}/bottom-right-{suf}.png")
    for kind in ("close", "hide", "maximize", "maximize-toggled", "menu", "shade", "shade-toggled", "stick", "stick-toggled"):
        for state in ("active", "inactive", "prelight", "pressed"):
            button(t, kind, state).save(f"{d}/{kind}-{state}.png")
    fg = "#%02x%02x%02x" % t["fg"]; fgi = "#%02x%02x%02x" % t["fgi"]
    with open(f"{d}/themerc", "w") as f:
        f.write(f"""# {name} - LuminaOS xfwm4 theme (generated by tools/gen-xfwm.py)
active_text_color={fg}
inactive_text_color={fgi}
title_alignment=left
title_horizontal_offset=12
title_vertical_offset_active=1
title_vertical_offset_inactive=1
full_width_title=true
title_shadow_active=false
title_shadow_inactive=false
button_offset=0
button_spacing=0
maximized_offset=0
shadow_delta_height=2
shadow_delta_width=0
shadow_delta_x=0
shadow_delta_y=-4
shadow_opacity=45
""")
    print("theme:", d)


if __name__ == "__main__":
    for n, t in THEMES.items():
        build(n, t)
